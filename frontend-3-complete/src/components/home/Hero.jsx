// Импортируем картинку как модуль.
//
// В Vite (и в большинстве современных сборщиков) картинку можно
// импортировать прямо в JSX — как переменную. Vite сам:
//   - найдёт файл по пути,
//   - скопирует его в итоговую сборку,
//   - подставит правильный URL в переменную heroSalon.
//
// Например, heroSalon станет строкой вроде
// "/assets/hero-salon-9a8b7c6d.png" — с хешем для кеширования.
//
// Так делать удобнее, чем писать путь строкой: если файл
// переименуют или переместят, сборка упадёт с понятной ошибкой,
// а не молча покажет битую картинку.
import heroSalon from "../../images/hero-salon.png";

// Hero — большая секция наверху главной страницы.
// Фоновое изображение салона, поверх — заголовок, описание
// и две кнопки.
//
// Пропсы:
//   onCtaServiceClick — колбэк, вызывается при клике
//                       на «Записаться на услугу».
//                       Клик по «Выбрать мастера» пока
//                       ни к чему не ведёт — страницы мастеров нет.
function Hero({ onCtaServiceClick }) {
  return (
    // <section> — семантически подходящий тег для отдельного
    // смыслового блока страницы.
    //
    // style={{ backgroundImage: ... }} — фон задаём inline, потому
    // что путь к картинке приходит из импорта. В CSS мы бы не смогли
    // подставить переменную из JS. Так что фон — единственное, что
    // логично задать здесь, а не в home.css.
    <section
      className="hero"
      style={{
        // linear-gradient — тёмный слой поверх картинки, чтобы
        // белый текст читался. 0.35 — прозрачность 35%.
        // url(${heroSalon}) — сюда подставляется строка с путём
        // к картинке, которую Vite сгенерировал после импорта.
        //
        // Обрати внимание на обратные кавычки `...` — это шаблонная
        // строка. Внутри ${...} можно вставить переменную.
        backgroundImage: `linear-gradient(0deg, rgba(0,0,0,0.35), rgba(0,0,0,0.35)), url(${heroSalon})`,
      }}
    >
      <div className="hero-text-container">
        {/* h1 — главный заголовок страницы. На одной странице
            должен быть только один h1. */}
        <h1 className="hero-title">Запланируйте время для себя</h1>
        <p className="hero-desc">
          Эксклюзивное пространство заботы о красоте и вашем умиротворении.
          Доверьте свой образ лучшим мастерам столицы.
        </p>
      </div>

      <div className="hero-ctas">
        {/* Первая кнопка — «Записаться на услугу».
            onClick={onCtaServiceClick} — при клике вызывается
            функция, переданная из HomeScreen, а та — из App.
            Цепочка: клик → onCtaServiceClick → App.goTo("services")
            → переключается экран на ServicesScreen. */}
        <button className="cta-service" onClick={onCtaServiceClick}>
          Записаться на услугу
        </button>

        {/* Вторая кнопка — «Выбрать мастера».
            Пока без onClick — экрана мастеров в проекте нет.
            Когда появится, добавим обработчик, как у первой. */}
        <button className="cta-master">Выбрать мастера</button>
      </div>
    </section>
  );
}

export default Hero;
