// Импортируем карточку мастера — она будет рендериться для
// каждого мастера в списке.
import MasterCard from "./MasterCard";

// MASTERS — массив мастеров из data/masters.js.
// Сейчас захардкожен, позже будет приходить с сервера.
// Каждый элемент — объект с полями id, name, role, rating, image.
import { MASTERS } from "../../data/masters";

// OurMasters — секция «Наши мастера» на главной странице.
//
// Состоит из трёх частей:
//   1. Заголовок секции («Наша гордость» + «Наши мастера»).
//   2. Сетка карточек — по одной на каждого мастера.
//   3. (Карточки — отдельный компонент MasterCard.)
//
// Компонент презентационный: ничего не хранит, пропсов не принимает.
// Данные берёт из data/masters.js.
function OurMasters() {
  return (
    // <section> — самостоятельный смысловой блок страницы.
    // Стили (отступы, фон) — в home.css.
    <section className="our-masters">
      {/* Заголовок секции. Устроен одинаково с «Популярные услуги»:
          сверху маленький тег (uppercase, зелёный),
          под ним — крупный заголовок h2. */}
      <div className="section-header">
        <span className="section-tag">Наша гордость</span>
        <h2 className="section-title">Наши мастера</h2>
      </div>

      {/* .masters-grid — flex-контейнер для карточек.
          Стили: display: flex, gap: 32px — то есть карточки
          выстраиваются в ряд с отступом. */}
      <div className="masters-grid">
        {/* Перебираем массив MASTERS и рендерим карточку для каждого.

            MASTERS.map(function (master) { return <MasterCard ... /> })

            — это выражение, которое возвращает массив JSX-элементов.
            React умеет рендерить массивы: он развернёт их в
            последовательность карточек.

            key={master.id} — обязательно. React использует ключ,
            чтобы эффективно обновлять список: если данные придут
            с сервера в другом порядке, React по ключам поймёт,
            какие карточки переместились, а какие новые.

            id мастера — идеальный ключ: он уникален и не меняется
            при обновлении данных. Индекс массива был бы хуже. */}
        {MASTERS.map(function (master) {
          return <MasterCard key={master.id} master={master} />;
        })}
      </div>
    </section>
  );
}

export default OurMasters;
