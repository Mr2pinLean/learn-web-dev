// В этом файле два компонента: LoadingState и EmptyState.
//
// Оба показывают по центру короткое сообщение. Один — «идёт загрузка»,
// другой — «данных нет». Разница только в смысле: LoadingState
// подразумевает, что данные вот-вот придут, EmptyState — что их
// не будет. Внешне же они сейчас абсолютно одинаковые.
//
// Почему два, а не один — чтобы в коде было понятно, что происходит:
// <LoadingState /> vs <EmptyState /> читается лучше, чем
// <Placeholder /> с флагом isLoading.
//
// Но разметка и стили у них совпадают — это дублирование.
// Если бы делали «по-взрослому», можно было бы:
//   - оставить один компонент <Message />,
//   - или вынести общую логику в базовый,
//   - или хотя бы стили унести в CSS-класс вместо inline.
// Для учебного примера оставлены два — зато наглядно видно,
// что такое «два похожих компонента».

// LoadingState — «идёт загрузка». Можно использовать, пока данные
// с сервера ещё не пришли. Сейчас в проекте не используется, но
// заготовка на будущее: если заменим SERVER_DATA на fetch,
// будем показывать <LoadingState message="Загрузка..." /> пока
// сервер не ответит.
export function LoadingState({ message }) {
  return (
    // style={{...}} — inline-стили. Здесь они оправданы: компонент
    // маленький, стили простые, выносить их в CSS-файл ради трёх
    // свойств нет смысла. Если стили усложнятся — переедем в CSS.
    //
    // Обрати внимание: имена свойств в camelCase (textAlign,
    // а не text-align), значения для размеров — строки с единицами
    // ("40px", а не 40).
    <div style={{ textAlign: "center", padding: "40px", color: "#6B6661" }}>
      {/* {message} — вставить значение пропса. Если родитель
          не передал message — покажется пустая строка. Можно
          задать значение по умолчанию в параметрах:
          function LoadingState({ message = "Загрузка..." }) */}
      {message}
    </div>
  );
}

// EmptyState — «данных нет». Используется в ServicesList, когда
// в выбранной категории не оказалось услуг.
//
// Устроен так же, как LoadingState. Отличается только смыслом —
// и это уже само по себе полезно: при чтении кода <EmptyState />
// сразу говорит, что ситуация — «пусто», а не «грузится».
export function EmptyState({ message }) {
  return (
    <div style={{ textAlign: "center", padding: "40px", color: "#6B6661" }}>
      {message}
    </div>
  );
}
