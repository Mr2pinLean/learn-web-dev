// Импортируем React. Нам он нужен не сам по себе, а ради
// React.Fragment — см. ниже. В современном React (17+) писать
// import React не обязательно, если не используем React.что-то.
// Но раз мы используем React.Fragment — импорт нужен.
import React from "react";

// StepIndicator — полоска из трёх шагов над формой бронирования.
// Показывает, на каком шаге пользователь находится сейчас,
// какие шаги уже пройдены, а какие ещё впереди.
//
// Используется на экранах:
//   - выбора услуг      (current=1),
//   - выбора даты/врем. (current=2),
//   - подтверждения     (current=3).
//
// Пропс:
//   current — номер текущего шага (1, 2 или 3).
export default function StepIndicator({ current }) {
  // Массив шагов. Каждый шаг — объект с номером, подписью
  // и полем active.
  //
  // active считается сразу при создании массива: current === N.
  // Это позволяет дальше в JSX не писать проверку ещё раз,
  // а просто читать step.active.
  //
  // Например, при current = 2:
  //   шаг 1: active = false
  //   шаг 2: active = true
  //   шаг 3: active = false
  const steps = [
    { number: 1, label: "Выбор услуги", active: current === 1 },
    { number: 2, label: "Дата и время", active: current === 2 },
    { number: 3, label: "Подтверждение", active: current === 3 },
  ];

  // Функция возвращает верстку кружка.
  // Если шаг пройден — с галочкой, иначе — с цифрой.
  //
  // Почему отдельная функция, а не разметка внутри map:
  // у кружка два варианта (пройден / не пройден), и удобно
  // выбирать их в одном месте по флагу isDone, а не запутывать
  // основной JSX тернарниками.
  //
  // Параметры:
  //   step    — объект шага ({ number, label, active })
  //   isDone  — true, если шаг уже пройден
  function circle(step, isDone) {
    // Пройденный шаг — светлый кружок с галочкой.
    // Фон (#c1a27e) задаётся через CSS-правило .step.done .circle,
    // а не здесь — потому что родитель добавляет класс "done".
    if (isDone) {
      return (
        <div className="circle">
          <span>✓</span>
        </div>
      );
    }

    // Не пройден. Если это активный (текущий) шаг — обычный кружок
    // с тёмным фоном и цифрой. Если будущий — кружок прозрачный
    // с тонкой рамкой (класс "empty").
    //
    // Тернарник !step.active ? "empty" : "" означает:
    //   если шаг НЕ активный → добавить класс "empty";
    //   иначе → ничего не добавлять.
    return (
      <div className={`circle ${!step.active ? "empty" : ""}`}>
        <span>{step.number}</span>
      </div>
    );
  }

  return (
    <div className="step-indicator">
      {/* Перебираем шаги. index нужен, чтобы понять, где рисовать
          соединительную линию — после последнего шага её нет. */}
      {steps.map((step, index) => {
        // isDone — шаг уже пройден. Условие: номер шага меньше
        // текущего. То есть при current = 2 первый шаг пройден,
        // а второй и третий — нет.
        const isDone = step.number < current;

        return (
          // React.Fragment нужен, чтобы вернуть несколько соседних
          // элементов без обёртки. Обычно React требует один
          // корневой элемент, но Fragment позволяет «склеить»
          // несколько без лишнего <div>.
          //
          // key={step.number} — уникальный ключ для React.
          // Номер шага подходит: он уникален (1, 2, 3).
          //
          // Короткая запись фрагмента — <>...</>, но с key работает
          // только <React.Fragment key={...}>. Поэтому здесь
          // длинный вариант.
          <React.Fragment key={step.number}>
            {/* Класс step done нужен, чтобы CSS подсветил кружок светлым.
                Правило в common.css:
                  .step.done .circle { background: #c1a27e; }
                То есть «если у .step есть класс .done — его кружок
                становится светлым». */}
            <div className={isDone ? "step done" : "step"}>
              {/* Кружок: либо с галочкой (если пройден), либо с цифрой. */}
              {circle(step, isDone)}

              {/* Подпись шага. Класс "light" делает текст светлее —
                  для неактивных шагов. Активный шаг — обычным цветом. */}
              <span className={`step-label ${!step.active ? "light" : ""}`}>
                {step.label}
              </span>

              {/* Соединительная линия между шагами. После последнего
                  шага её не рисуем — поэтому index < steps.length - 1.
                  Для 3 шагов линия будет после шага 0 и после шага 1,
                  но не после шага 2. */}
              {index < steps.length - 1 && <div className="step-line"></div>}
            </div>
          </React.Fragment>
        );
      })}
    </div>
  );
}
