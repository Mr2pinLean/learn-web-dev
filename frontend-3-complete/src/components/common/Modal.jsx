// Modal — универсальная обёртка для модальных окон.
//
// Сам по себе он ничего не показывает. Его задача — предоставить
// «рамку»: затемнённый фон, контейнер по центру и анимацию появления.
// Что именно внутри — решает родитель, который передаёт содержимое
// через проп children.
//
// В нашем проекте Modal используется только на странице подтверждения
// для показа окна «Запись подтверждена». Внутрь передаётся
// <ConfirmationModal /> — компонент с содержимым этого конкретного окна.
//
// Пропсы:
//   open     — true / false. Если false — модалка не рендерится вовсе.
//   children — что показать внутри модалки (JSX).
function Modal({ open, children }) {
  // Ранний выход: если модалку не надо показывать — возвращаем null.
  // React ничего не отрисует. Это простой способ «скрыть» компонент:
  // не display: none, а вообще не создавать DOM-элемент.
  //
  // Плюс: когда open снова станет true, Modal отрендерится заново,
  // и анимация появления (если её добавим) сработает правильно.
  if (!open) return null;

  return (
    // Используем HTML-тег <dialog>.
    //
    // <dialog> — нативный тег браузера для модальных окон. У него
    // есть встроенный ::backdrop (затемнение фона) и методы
    // showModal() / close().
    //
    // Но! Мы не вызываем showModal() — потому что это потребовало
    // бы useEffect и useRef, а мы стараемся обойтись без хуков
    // в этой части. Вместо этого ставим атрибут open — браузер
    // показывает диалог, но без modal-режима. Соответственно:
    //   - ::backdrop не срабатывает,
    //   - фокус не блокируется,
    //   - Esc не закрывает.
    //
    // Затемнение фона мы сделали вручную через CSS: в modal.css
    // есть правило .confirmation-modal[open]::before, которое
    // рисует тёмный слой под содержимым.
    //
    <dialog className="confirmation-modal" open>
      {/* .modal-content — белая карточка с тенью и скруглениями.
          Она оборачивает всё, что передал родитель.
          Стили — в modal.css. */}
      <div className="modal-content">{children}</div>
    </dialog>
  );
}

export default Modal;
