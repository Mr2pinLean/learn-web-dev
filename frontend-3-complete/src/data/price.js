// formatPrice — маленькая утилита для форматирования цены.
//
// Зачем нужна отдельная функция, если можно написать одну строчку
// прямо в JSX:
//
//   {service.price.toLocaleString("ru-RU")} ₽
//
// Затем, что цена используется в нескольких местах:
//   - в BookingDetails («К оплате в салоне»),
//   - в ConfirmationModal («К оплате»),
//   - потенциально — в других местах.
//
// Если формат изменится (например, добавят копейки, символ ₽
// поставят перед числом, введут разделитель для тысяч в другом
// стиле), править придётся в одном месте, а не в каждом компоненте.
//
// Параметры:
//   price — число, например 3200
//
// Возвращает:
//   строку с числом и знаком рубля, например "3 200 ₽"
export function formatPrice(price) {
  // toLocaleString("ru-RU") форматирует число по правилам
  // русской локали:
  //   4500   → "4 500"
  //   12500  → "12 500"
  //   1234567 → "1 234 567"
  //
  // Разделитель между разрядами — неразрывный пробел (U+00A0).
  // Это значит, что «4 500 ₽» никогда не разорвётся на две строки:
  // «4» останется с «500» и с «₽». Если бы использовали обычный
  // пробел, при переносе строки «₽» мог улететь на следующую строку.
  //
  // + " ₽" — дописываем знак рубля. Пробел перед ним — обычный.
  return price.toLocaleString("ru-RU") + " ₽";
}