// ============================================================
// 5. ОТРИСОВКА И ОБРАБОТЧИКИ
// ============================================================
//
// На главной странице нет ни данных с сервера, ни состояния,
// ни рендера — только статичная вёрстка и пара кнопок, которые
// куда-то ведут. Поэтому этот файл короче остальных: в нём
// только обработчики кликов.

// setupCtaServiceButton — вешает обработчик на кнопку
// «Записаться на услугу» в hero-секции.
//
// По клику переходим на страницу выбора услуг (services.html).
// Проверка `if (ctaService)` нужна на случай, если элемент
// не нашёлся — тогда мы просто не вешаем обработчик, и страница
// не падает с ошибкой.
function setupCtaServiceButton() {
  const ctaService = document.querySelector(".cta-service");
  if (ctaService) {
    ctaService.addEventListener("click", function () {
      window.location.href = "services.html";
    });
  }
}

// setupLogoClick — клик по логотипу в шапке.
// С главной никуда не ведёт, но обработчик всё равно вешаем:
// пользователь по привычке может кликнуть по логотипу, ожидая
// вернуться «домой». Переход на index.html просто перезагрузит
// страницу — эффект тот же, что и «ничего не произошло».
function setupLogoClick() {
  const logo = document.querySelector(".logo-text");
  if (logo) {
    logo.addEventListener("click", function () {
      window.location.href = "index.html";
    });
  }
}

// ============================================================
// ИНИЦИАЛИЗАЦИЯ
// ============================================================
//
// init() собирает все обработчики и вызывается один раз,
// когда DOM готов.

function init() {
  setupCtaServiceButton();
  setupLogoClick();
}

// Ждём, пока браузер построит DOM, потом запускаем init.
// Без этого querySelector в init() не нашёл бы элементы.
document.addEventListener("DOMContentLoaded", function () {
  init();
});
