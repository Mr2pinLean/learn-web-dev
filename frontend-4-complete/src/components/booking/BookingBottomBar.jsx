// Импортируем массивы для форматирования даты.
// MONTHS_GENITIVE — названия месяцев в родительном падеже
//   ("января", "февраля"...) — чтобы написать «17 октября», а не «17 Октябрь».
// DAYS_OF_WEEK — названия дней недели ("Воскресенье", "Понедельник"...).
import { MONTHS_GENITIVE, DAYS_OF_WEEK } from "../../data/date";

// BookingBottomBar — нижняя панель на экране выбора даты.
// Показывает, что пользователь уже выбрал, и кнопку «Далее».
//
// Пропсы:
//   day          — выбранный день месяца (число, например 17)
//   month        — выбранный месяц (0 = январь, 9 = октябрь)
//   year         — выбранный год (например, 2026)
//   selectedTime — выбранное время строкой ("12:00") или null
//   onNext       — колбэк, вызывается при клике на «Далее»
function BookingBottomBar({ day, month, year, selectedTime, onNext }) {
  // Собираем объект Date, чтобы узнать день недели.
  // new Date(year, month, day) — принимает месяц от 0, поэтому
  // month передаём как есть.
  const dateObj = new Date(year, month, day);

  // getDay() возвращает индекс дня недели: 0 — воскресенье, 1 — понедельник,
  // ..., 6 — суббота. По этому индексу достаём название из DAYS_OF_WEEK.
  const dayName = DAYS_OF_WEEK[dateObj.getDay()];

  // Название месяца в родительном падеже по индексу.
  const monthName = MONTHS_GENITIVE[month];

  // Если время ещё не выбрано — покажем заглушку.
  // Тернарный оператор: если selectedTime не null, используем его,
  // иначе — строку "время не выбрано".
  const timePart = selectedTime ? selectedTime : "время не выбрано";

  return (
    <div className="bottom-bar">
      {/* Левая часть — что выбрано. */}
      <div className="selected-info">
        <span className="label">Выбранная дата и время:</span>
        {/* Склеиваем строку: «Пятница, 17 октября 2026 • 12:00».
            В JSX фигурные скобки {} — это «вставить значение переменной».
            Обычный текст пишется как есть, переменные — в скобках. */}
        <span className="value">
          {dayName}, {day} {monthName} {year} • {timePart}
        </span>
      </div>

      {/* Правая часть — кнопка «Далее».
          onClick={onNext} значит: при клике вызвать функцию,
          которую передал родитель (BookingScreen). Что именно
          она делает — не наша забота. Может перейти на другой
          экран, может что-то сохранить — решает родитель.
          Это и есть «колбэк»: дочерний компонент сообщает наверх,
          что что-то произошло. */}
      <button className="booking-next-btn" onClick={onNext}>
        Далее
      </button>
    </div>
  );
}

export default BookingBottomBar;
